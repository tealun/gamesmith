#!/usr/bin/env python3
"""Copy the engine-independent core and the config tables into an engine project (template, Cocos Creator layout).

    python3 tools/sync_to_engine.py <path-to-engine-project>

- core/*.mjs|*.ts -> <project>/assets/scripts/core/   (each copy starts with a GENERATED header; never edit copies)
- config/**/*.json -> <project>/assets/pack/config/  (a custom bundle, loaded after the first frame draws a loading screen)

Engine .meta files next to the copies are kept (their uuids are committed with the project). Copies whose source
was deleted are removed together with their .meta. Adapt the paths and the import rewrite to your engine.
"""
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = "// GENERATED by tools/sync_to_engine.py from core/ — edit the original, not this copy.\n"

if len(sys.argv) != 2:
    sys.exit(__doc__)
project = pathlib.Path(sys.argv[1]).resolve()
if not (project / "assets").is_dir():
    sys.exit(f"sync_to_engine: {project} has no assets/ folder (not an engine project?)")

# core: drop our old generated copies (recognised by the header), then write fresh ones
core_out = project / "assets/scripts/core"
core_out.mkdir(parents=True, exist_ok=True)
for old in core_out.iterdir():
    if old.suffix in (".ts", ".mjs", ".js") and old.read_text(encoding="utf-8").startswith(HEADER):
        old.unlink()
n = 0
for src in sorted((ROOT / "core").glob("*")):
    if src.suffix not in (".ts", ".mjs"):
        continue
    # some engine bundlers reject explicit extensions in relative imports ('./x.ts' / './x.mjs'): strip them
    text = re.sub(r"""(from\s+['"]\.{1,2}/[^'"]+)\.(ts|mjs)(['"])""", r"\1\3", src.read_text(encoding="utf-8"))
    (core_out / (src.stem + ".ts")).write_text(HEADER + "// @ts-nocheck\n" + text if src.suffix == ".mjs" else HEADER + text, encoding="utf-8")
    n += 1

# config: copy file by file, keep .meta, remove configs that no longer exist
cfg_out = project / "assets/pack/config"
src_files = {p.relative_to(ROOT / "config") for p in (ROOT / "config").rglob("*.json")}
for old in list(cfg_out.rglob("*.json")) if cfg_out.exists() else []:
    if old.relative_to(cfg_out) not in src_files:
        old.unlink()
        meta = old.with_name(old.name + ".meta")
        if meta.exists():
            meta.unlink()
for rel in sorted(src_files):
    dst = cfg_out / rel
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ROOT / "config" / rel, dst)
print(f"sync_to_engine: {n} core file(s), {len(src_files)} config file(s) -> {project}")
