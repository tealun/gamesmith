#!/usr/bin/env python3
"""Copy the engine-independent core and the config tables into an engine project (template, Cocos Creator layout).

    python3 sync_to_engine.py <path-to-engine-project>

- CORE_FILES (sim.mjs)              -> <project>/assets/scripts/core/<name>.ts  (GENERATED header; never edit copies)
- CONFIG_FILES + chunks_*.json      -> <project>/assets/pack/config/            (a custom bundle, loaded after the first
                                                                              frame draws a loading screen)

Engine .meta files next to the copies are kept (their uuids are committed with the project). A chunk library
(chunks_*.json) whose source was deleted is removed together with its .meta; other files in the config folder are
left alone, so tables you keep only in the engine project are never touched. In a real project the core lives in its own folder (game/core)
and the tables in config/: point SRC_CORE / SRC_CONFIG there and adapt the import rewrite to your engine.
"""
import pathlib
import re
import shutil
import sys

HERE = pathlib.Path(__file__).resolve().parent
SRC_CORE = HERE
SRC_CONFIG = HERE
CORE_FILES = ["sim.mjs"]
CONFIG_FILES = ["player.json", "entities.json", "levels.json", "solver.json"]
HEADER = "// GENERATED by sync_to_engine.py from the core — edit the original, not this copy.\n"

if len(sys.argv) != 2:
    sys.exit(__doc__)
project = pathlib.Path(sys.argv[1]).resolve()
if not (project / "assets").is_dir():
    sys.exit(f"sync_to_engine: {project} has no assets/ folder (not an engine project?)")

# core: drop our old generated copies (recognised by the header), then write fresh ones
core_out = project / "assets/scripts/core"
core_out.mkdir(parents=True, exist_ok=True)
for old in core_out.iterdir():
    if old.suffix in (".ts", ".mjs", ".js") and old.read_text(encoding="utf-8").startswith(HEADER):
        old.unlink()
for name in CORE_FILES:
    src = SRC_CORE / name
    # some engine bundlers reject explicit extensions in relative imports ('./x.ts' / './x.mjs'): strip them
    text = re.sub(r"""(from\s+['"]\.{1,2}/[^'"]+)\.(ts|mjs)(['"])""", r"\1\3", src.read_text(encoding="utf-8"))
    nocheck = "// @ts-nocheck\n" if src.suffix == ".mjs" else ""
    (core_out / (src.stem + ".ts")).write_text(HEADER + nocheck + text, encoding="utf-8")

# config: copy file by file, keep .meta, remove configs that no longer exist
cfg_out = project / "assets/pack/config"
names = set(CONFIG_FILES) | {p.name for p in SRC_CONFIG.glob("chunks_*.json")}
for old in list(cfg_out.glob("chunks_*.json")) if cfg_out.exists() else []:   # only copies this script made
    if old.name not in names:
        old.unlink()
        meta = old.with_name(old.name + ".meta")
        if meta.exists():
            meta.unlink()
cfg_out.mkdir(parents=True, exist_ok=True)
for name in sorted(names):
    shutil.copyfile(SRC_CONFIG / name, cfg_out / name)
print(f"sync_to_engine: {len(CORE_FILES)} core file(s), {len(names)} config file(s) -> {project}")
